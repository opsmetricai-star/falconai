export type PageDef = {
  path: string; // e.g. platform/endpoint-security
  title: string;
  eyebrow: string;
  tagline: string;
  summary: string;
  features: { title: string; body: string }[];
};

const SECTION_EYEBROW: Record<string, string> = {
  platform: "FalconAI Platform",
  services: "FalconAI Services",
  solutions: "Solutions",
  "why-falconai": "Why FalconAI",
  resources: "Resources",
  "cyber-si-lab": "Cyber SuperIntelligence Lab",
  about: "Company",
  partners: "Partners",
  support: "Support",
  pricing: "Pricing",
};

function p(path: string, title: string, tagline: string, summary: string, ...f: string[]): PageDef {
  return {
    path,
    title,
    tagline,
    summary,
    eyebrow: SECTION_EYEBROW[path.split("/")[0]] ?? "FalconAI",
    features: f.map((x) => {
      const [t, b] = x.split("|");
      return { title: t, body: b };
    }),
  };
}

